# Usage: gen_bits.py <dir containing model.safetensors> <out dir>
# Writes <out>/Bits/*.lean: the float16 bits of the six layers and the rows used by pythia/interval/.
import numpy as np, os, sys
from safetensors.numpy import load_file
P, OUT = sys.argv[1], sys.argv[2]  # dir containing model.safetensors, output dir
sd = load_file(P + "/model.safetensors")
for k, v in sd.items(): assert v.dtype == np.float16
def pack(a):
    a = np.ascontiguousarray(a.astype('<f2'))
    u = a.view('<u2')
    assert not np.any((u >> 10) & 31 == 31), "inf/nan"
    return int.from_bytes(a.tobytes(), 'little')
def hx(n): return "0x%x" % n
def vecdef(name, a):
    return "def %s : Nat := %s\n" % (name, hx(pack(a)))
def matdef(name, a):
    rows = ",\n  ".join(hx(pack(a[r])) for r in range(a.shape[0]))
    return "def %s : List Nat := [\n  %s]\n" % (name, rows)
os.makedirs(OUT + "/Bits", exist_ok=True)
names = [("ln1g","input_layernorm.weight",0),("ln1b","input_layernorm.bias",0),("qkvW","attention.query_key_value.weight",1),("qkvB","attention.query_key_value.bias",0),
         ("dW","attention.dense.weight",1),("dB","attention.dense.bias",0),("ln2g","post_attention_layernorm.weight",0),("ln2b","post_attention_layernorm.bias",0),
         ("fcW","mlp.dense_h_to_4h.weight",1),("fcB","mlp.dense_h_to_4h.bias",0),("pjW","mlp.dense_4h_to_h.weight",1),("pjB","mlp.dense_4h_to_h.bias",0)]
for l in range(6):
    s = "/-! Raw float16 bits of `gpt_neox.layers.%d.*` of EleutherAI/pythia-14m (safetensors, main).\nA vector is the little-endian integer of its byte buffer (entry `i` = bits `16 i .. 16 i + 15`); a matrix is the list of its rows, each packed the same way. Generated by tools/gen_bits.py. -/\n\nnamespace PRO.Bits.L%d\n\n" % (l, l)
    for nm, key, ismat in names:
        a = sd["gpt_neox.layers.%d.%s" % (l, key)]
        s += (matdef if ismat else vecdef)(nm, a) + "\n"
    s += "end PRO.Bits.L%d\n" % l
    open(OUT + "/Bits/L%d.lean" % l, "w").write(s)
TOK = {"bos": 0, "comma": 13, "red": 2502, "blue": 4797}
s = "/-! Raw float16 bits of the embedding rows (`gpt_neox.embed_in.weight`) of the four tokens used by the prompts, of the unembedding rows (`embed_out.weight`) of the two candidate tokens, and of `gpt_neox.final_layer_norm`. Packed as in `PRO.Bits.L0`. Generated by tools/gen_bits.py. -/\n\nnamespace PRO.Bits.E\n\n"
for nm, t in TOK.items():
    s += "/-- `embed_in` row of token %d. -/\n" % t + vecdef("in_" + nm, sd["gpt_neox.embed_in.weight"][t]) + "\n"
for nm in ("red", "blue"):
    s += "/-- `embed_out` row of token %d. -/\n" % TOK[nm] + vecdef("out_" + nm, sd["embed_out.weight"][TOK[nm]]) + "\n"
s += vecdef("lnfg", sd["gpt_neox.final_layer_norm.weight"]) + "\n" + vecdef("lnfb", sd["gpt_neox.final_layer_norm.bias"]) + "\n"
s += "end PRO.Bits.E\n"
open(OUT + "/Bits/E.lean", "w").write(s)

# Usage: gen_weights.py <dir containing model.safetensors> <out dir>
# Writes <out>/W/*.lean: every parameter of pythia-14m as its float16 bit pattern.
# A row of m float16 entries is packed into one natural number: entry j occupies bits [16 j, 16 j + 16).
import sys, os, numpy as np
from safetensors.numpy import load_file
P, OUT = sys.argv[1], sys.argv[2]
T = load_file(P + "/model.safetensors")
os.makedirs(OUT + "/W", exist_ok=True)
total = 0
def bits(a):
    a = np.asarray(a)
    assert a.dtype == np.float16, a.dtype
    u = a.view(np.uint16)
    assert not np.any(((u >> 10) & 31) == 31), "inf/nan"
    return u
def pack(u):  # 1-d uint16 -> hex literal
    global total
    total += u.size
    return "0x" + u[::-1].astype(">u2").tobytes().hex()
def vec(name, u): return f"def {name} : Nat := {pack(u)}\n"
def mat(name, u): return f"def {name} : List Nat := [\n" + ",\n".join(pack(r) for r in u) + "]\n"
HEAD = "/-! Generated by tools/gen_weights.py from model.safetensors: float16 bit patterns,\none natural number per row, entry `j` in bits `[16 j, 16 j + 16)`. -/\n\nnamespace CON\nnamespace W\n"
for i in range(6):
    p = f"gpt_neox.layers.{i}."
    s = HEAD + f"namespace L{i}\n"
    s += vec("ln1g", bits(T[p + "input_layernorm.weight"])) + vec("ln1b", bits(T[p + "input_layernorm.bias"]))
    s += vec("ln2g", bits(T[p + "post_attention_layernorm.weight"])) + vec("ln2b", bits(T[p + "post_attention_layernorm.bias"]))
    s += mat("qkvW", bits(T[p + "attention.query_key_value.weight"])) + vec("qkvB", bits(T[p + "attention.query_key_value.bias"]))
    s += mat("oW", bits(T[p + "attention.dense.weight"])) + vec("oB", bits(T[p + "attention.dense.bias"]))
    s += mat("fW", bits(T[p + "mlp.dense_h_to_4h.weight"])) + vec("fB", bits(T[p + "mlp.dense_h_to_4h.bias"]))
    s += mat("pW", bits(T[p + "mlp.dense_4h_to_h.weight"])) + vec("pB", bits(T[p + "mlp.dense_4h_to_h.bias"]))
    s += f"end L{i}\nend W\nend CON\n"
    open(f"{OUT}/W/L{i}.lean", "w").write(s)
s = HEAD + vec("lnfg", bits(T["gpt_neox.final_layer_norm.weight"])) + vec("lnfb", bits(T["gpt_neox.final_layer_norm.bias"])) + "end W\nend CON\n"
open(f"{OUT}/W/Fin.lean", "w").write(s)
CH, PER = 256, 4   # rows per chunk, chunks per module
for tag, key in [("E", "gpt_neox.embed_in.weight"), ("U", "embed_out.weight")]:
    u = bits(T[key]); nch = (u.shape[0] + CH - 1) // CH; nmod = (nch + PER - 1) // PER
    for m in range(nmod):
        s = HEAD
        for c in range(m * PER, min(nch, (m + 1) * PER)):
            s += mat(f"{tag.lower()}{c}", u[c * CH:(c + 1) * CH])
        s += "end W\nend CON\n"
        open(f"{OUT}/W/{tag}{m}.lean", "w").write(s)
    s = "".join(f"import CON.W.{tag}{m}\n" for m in range(nmod)) + "\n/-! Row chunks of `" + key + "`: row `t` is entry `t % 256` of chunk `t / 256`. -/\n\nnamespace CON\nnamespace W\n"
    s += f"def {tag.lower()}Chunks : List (List Nat) := [\n" + ",\n".join(f"{tag.lower()}{c}" for c in range(nch)) + "]\nend W\nend CON\n"
    open(f"{OUT}/W/{tag}Index.lean", "w").write(s)
print("parameters written:", total, "tensors:", len(T), "sum of sizes:", sum(v.size for v in T.values()))
